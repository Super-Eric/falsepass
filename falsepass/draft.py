"""Draft an audit report and a cross-environment overview from recorded results.

`falsepass draft <env>` writes `REPORT.draft.md`: every group of failing probes becomes a
*candidate* finding with its numbers and one exact example, pre-filled where the data
allows and marked TODO where a person has to judge. It is a starting point for the
manual review, never a substitute: nothing in a draft has been reproduced or interpreted.
"""

from __future__ import annotations

import json
from collections import defaultdict
from pathlib import Path
from typing import Any

from falsepass import report

MEANING = {
    "P1": "the reference answer is not given full reward",
    "P2": "a harmless variation of the correct answer loses reward",
    "P3": "an empty completion is rewarded",
    "P4": "echoing the prompt is rewarded",
    "P5": "listing several candidate answers is rewarded",
    "P6": "a wrong answer in the right format is rewarded",
    "P7": "a confident wrong answer is rewarded",
    "P8": "a note addressed to the grader changes the score",
    "P9": "a retracted or denied answer is rewarded",
    "P10": "malformed output is rewarded, or makes the reward code raise",
    "P11": "the same completion gets different scores",
    "P12": "the dataset has structural defects",
    "T4": "an episode's result depends on what ran before it",
    "T5": "a policy that never answers is not cut off, or is rewarded",
    "T6": "a policy that calls tools without reading the task is rewarded, or makes the reward code raise",
    "T7": "a correct answer given after one tool call loses reward (messages counted as turns)",
    "P13": "NaN, Infinity or a fractional count is accepted, or makes the reward code raise",
    "P14": "a correct answer loses reward when the reply also names its answer format",
    "P15": "a denied or hedged answer written inside the answer slot gets full credit",
    "P16": "a JSON reply whose free-text fields are the prompt pasted in is paid like the reference",
    "P17": "a JSON reply with one short field followed by a denial everywhere is paid like the reference: that field is not read to its end",
    "C0": "the key written as the output file is not paid in full (no automatic submission format)",
    "C1": "a key with NaN, Infinity or fractional counts written as the output file is paid in full, or makes scoring raise",
    "C2": "an empty, truncated or copied output file is paid in full",
    "S1": "search found a rewarded completion that never mentions the reference",
    "S2": "search found a correct completion that loses reward",
    "S3": "search found a rewarded completion that mentions the reference without committing to it",
    "X1": "environment-specific probe",
}
NEEDS_JUDGEMENT = {"P2", "S2", "P14", "T7"}  # strictness versus defect is a human call; P14/T7 only matter for some harnesses


def _stats(rows: list[dict[str, Any]]) -> str:
    scores = [r["score"] for r in rows if r["score"] is not None]
    if not scores:
        if all(r["probe"] == "P12" for r in rows):
            return "no score (a dataset check: nothing is scored)"
        return "no score (reward code raised)"
    return f"min {min(scores):.3g}, mean {sum(scores) / len(scores):.3g}, max {max(scores):.3g}"


def _inline(full: Any, stored: Any, preview: Any) -> str:
    text = preview(full, 220) if isinstance(full, str) else str(stored)[:220]
    return text.replace("\n", " ⏎ ").replace("`", "'")


def draft(audit_dir: Path) -> Path:
    from falsepass.probes import preview

    payload = json.loads((audit_dir / "probe-results.json").read_text())
    meta, results = payload["meta"], payload["results"]
    stored = audit_dir / "completions.json"
    completions = json.loads(stored.read_text()) if stored.is_file() else {}
    head = report.headline(results)
    adapter = meta.get("adapter")
    versions = " · ".join(f"{k} {v}" for k, v in meta["versions"].items())
    lines = [
        f"# Audit: {meta['environment']} — DRAFT",
        "",
        "> Generated by `falsepass draft`. **Not reviewed.** Every item below is a candidate: reproduce it "
        "(`falsepass repro`), read the reward code, decide whether it is a defect or a design choice, "
        "then rewrite this file as REPORT.md and delete what does not hold.",
        "",
        f"{meta['date']} · {versions} · falsepass {meta['falsepass']} · no model used · {meta['examples']} examples, seed {meta['seed']}",
        "",
        "## Summary",
        "",
        "TODO: two or three sentences — what the environment does, what was found, overall verdict.",
        "",
        f"- False-pass ceiling {report._fmt(head['false_pass_ceiling'])} of {report._fmt(meta['max_reward'])} (via {head['false_pass_via']})",
        f"- Lazy-policy reward {report._fmt(head['lazy_policy_reward'])} (via {head['lazy_policy_via']})",
        f"- False-fail rate {report._fmt(head['false_fail_rate'])} over {head['known_good']} known-good completions",
        f"- Scoring raised or timed out on {head['scoring_errors']} completions",
    ]
    if isinstance(adapter, dict):
        lines.append(f"- Adapter inferred: format `{adapter['format']}`, answers {adapter['answers']}; control: {adapter.get('validity', 'ok')}")
        validity = adapter.get("validity", "ok")
        if validity.startswith("no control"):
            lines += ["", "**No control was possible (no reference answers): the rows below say what answer-free replies earn, "
                          "nothing about correct ones. Give references (`--answers`, `tasks.json`) before calling anything a false pass.**"]  # fmt: skip
        elif validity != "ok":
            lines += ["", "**The control failed. Do not report anything from this run before resolving that.**"]

    groups: dict[tuple[str, str], list[dict[str, Any]]] = defaultdict(list)
    for r in results:
        groups[(r["probe"], r["name"])].append(r)
    hints = payload.get("static") or []
    lines += ["", "## Candidate findings", ""]
    number = 0
    for (probe, name), rows in groups.items():
        failed = [r for r in rows if not r["passed"]]
        if not failed:
            continue
        number += 1
        variants = sorted({r["variant"] for r in failed})
        # the shortest failing completion shows the defect best (a 2 KB preview hides the `=`)
        first = min(failed, key=lambda r: len(completions.get(r.get("completion_id") or "") or r["completion"] or ""))
        backing = [h for h in hints if probe in h["confirm_with"] and h["verdict"].startswith("confirmed")]
        lines += [
            f"### C{number} — {MEANING.get(probe, name)}  [severity: TODO]",
            "",
            f"- Check: {probe} {name}; failing variants: {', '.join(variants)}",
            f"- Observed: {len(failed)} of {len(rows)} runs failed; expected {first['expected']}. By failing variant "
            "(failed / runs, scores of the failed runs): "
            + "; ".join(f"{v} {sum(1 for r in failed if r['variant'] == v)}/{sum(1 for r in rows if r['variant'] == v)}, "
                        f"{_stats([r for r in failed if r['variant'] == v])}" for v in variants),
            f"- Example `{first['example']}`, variant `{first['variant']}`: {first['detail'] or 'see results'}",
            f"- Completion (start and end; full text: `falsepass results {audit_dir.name} --completion {first.get('completion_id') or '?'}`): "
            f"`{_inline(completions.get(first.get('completion_id') or ''), first['completion'], preview)}`",
        ]
        for h in backing:
            lines.append(f"- Source hint: `{h['file']}:{h['line']}` {h['rule']} — `{h['evidence']}`")
        if probe in NEEDS_JUDGEMENT:
            lines.append("- Judgement needed: is this variation one the prompt allows? If the prompt forbids it, this is strictness, not a defect.")
        if isinstance(adapter, dict) and "open-ended" in adapter.get("answers", "") and name == "task_independence":
            lines.append("- Note: for open-ended tasks this shows the reward barely depends on which task was set. It is not a wrong answer being accepted.")
        lines += ["- Cause: TODO (read the reward code)", "- Impact on training: TODO", "- Suggested fix: TODO", ""]
    if number == 0:
        lines += ["None: every probe passed.", ""]

    lines += ["## Checks that passed", "", "| Check | Runs | Scores |", "|---|---|---|"]
    for (probe, name), rows in groups.items():
        if all(r["passed"] for r in rows):
            if probe == "P11":  # the reference and a wrong reply, each repeated: one line each, not pooled
                for variant in sorted({r["variant"] for r in rows}):
                    some = [r for r in rows if r["variant"] == variant]
                    lines.append(f"| {probe} {name} ({variant}) | {len(some)} | {_stats(some)} |")
                continue
            lines.append(f"| {probe} {name} | {len(rows)} | {_stats(rows)} |")
    lines += [
        "",
        "## Limitations of this audit",
        "",
        "- Synthetic probes only; no model rollouts.",
        "- Labels were not checked against the tasks.",
        "- TODO: runtime, platform, sample size, anything specific to this environment.",
    ]
    if isinstance(adapter, dict):
        lines.append("- The adapter was inferred, not written: the answer format and the notion of a wrong answer are the tool's guesses.")
    path = audit_dir / "REPORT.draft.md"
    path.write_text("\n".join(lines) + "\n")
    return path


SEVERITIES = ("Critical", "High", "Medium", "Low")


def findings(report: Path) -> dict[str, int]:
    """Count findings by severity from the `### F<n> — title  [Severity]` headings of a report."""
    import re

    found = re.findall(r"^### F\d+ — .*\[(Critical|High|Medium|Low)\]\s*$", report.read_text(), re.M)
    return {level: found.count(level) for level in SEVERITIES}


def is_unreviewed(report: Path) -> bool:
    """A report an agent wrote and no reviewer has passed yet carries this marker near the top."""
    return "DRAFT — not reviewed" in "\n".join(report.read_text().splitlines()[:12])


def _status(report_md: Path, counts: dict[str, int]) -> str:
    status = ", ".join(f"{n} {level}" for level, n in counts.items() if n) or "no finding"
    return f"report not reviewed yet ({status})" if is_unreviewed(report_md) else status


def overview(audits: Path) -> str:
    """One row per audited environment, from whatever is on disk. Finding counts are read
    from the report headings, so totals quoted elsewhere can be checked against this."""
    rows = []
    totals = dict.fromkeys(SEVERITIES, 0)
    reports = 0
    # `<env>-upstream/` audits an unreleased source version of an environment already audited
    # at its Hub release. Its findings mostly repeat that report's, so they are listed but
    # kept out of the headline totals.
    upstream = dict.fromkeys(SEVERITIES, 0)
    upstream_reports = 0

    def count(audit_dir: Path, counts: dict[str, int]) -> None:
        nonlocal reports, upstream_reports
        if is_unreviewed(audit_dir / "REPORT.md"):
            return
        into = upstream if audit_dir.name.endswith("-upstream") else totals
        if into is upstream:
            upstream_reports += 1
        else:
            reports += 1
        for level in SEVERITIES:
            into[level] += counts[level]
    for audit_dir in sorted(p for p in audits.iterdir() if (p / "probe-results.json").is_file() or (p / "REPORT.md").is_file()):
        if not (audit_dir / "probe-results.json").is_file():
            # Audited with hand-written scripts only (tool-use or judge environments): no probe run to tabulate.
            counts = findings(audit_dir / "REPORT.md")
            count(audit_dir, counts)
            status = _status(audit_dir / "REPORT.md", counts)
            title = (audit_dir / "REPORT.md").read_text().splitlines()[0]
            name = title.removeprefix("# Audit:").split("@")[0].strip()
            rows.append(f"| `{name}` | scripted policies, no probe run | — | — | — | — | — | — | {status} |")
            continue
        payload = json.loads((audit_dir / "probe-results.json").read_text())
        meta, head = payload["meta"], report.headline(payload["results"])
        adapter = meta.get("adapter")
        if isinstance(adapter, dict):
            how = "inferred" if adapter.get("validity", "ok") == "ok" else "inferred — inconclusive"
        else:
            how = "hand-written"
        if (audit_dir / "REPORT.md").is_file():
            counts = findings(audit_dir / "REPORT.md")
            count(audit_dir, counts)
            status = _status(audit_dir / "REPORT.md", counts)
        else:
            status = "draft only" if (audit_dir / "REPORT.draft.md").is_file() else "probe run only, no report"
        confirmed = sum(1 for h in payload.get("static") or [] if h["verdict"].startswith("confirmed"))
        rows.append(
            f"| `{meta['environment']}` | {how} | {report._fmt(meta['max_reward'])} | {report._fmt(head['false_pass_ceiling'])} | "
            f"{report._fmt(head['lazy_policy_reward'])} | {report._fmt(head['false_fail_rate'])} | {head['scoring_errors']} | "
            f"{confirmed}/{len(payload.get('static') or [])} | {status} |"
        )
    summary = (
        f"{reports} environments with a reviewed report; {sum(totals.values())} findings: "
        + ", ".join(f"{n} {level}" for level, n in totals.items())
        + ". Counted from the report headings."
        + (
            f" Not in these totals: {upstream_reports} re-audit(s) of an unreleased upstream version "
            f"({sum(upstream.values())} findings: " + ", ".join(f"{n} {level}" for level, n in upstream.items()) + ")."
            if upstream_reports
            else ""
        )
        + " The numeric columns are the latest probe run in automatic\n"
        "or adapter mode and can differ from numbers in a report, which may come from a targeted repro on\n"
        "other examples; where they disagree, the report is the reviewed statement.\n\n"
    )
    header = (
        "| Environment | Adapter | Reference reward | False-pass ceiling | Lazy-policy reward | False-fail rate | "
        "Scoring errors | Static hints confirmed | Findings in REPORT.md |\n|---|---|---|---|---|---|---|---|---|\n"
    )
    return summary + header + "\n".join(rows) + "\n"
