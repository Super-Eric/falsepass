LOAD_INSPECT = '''
import importlib
import importlib.util
from pathlib import Path

from inspect_ai.model import ChatMessageUser, GenerateConfig, ModelOutput, get_model
from inspect_ai.model._model import init_active_model
from inspect_ai.scorer import Target, value_to_float
from inspect_ai.solver import TaskState


def load_task(spec, args):
    target, _, function = spec.partition("@")
    if target.endswith(".py"):
        loaded = importlib.util.spec_from_file_location("task_module", Path(target).resolve())
        module = importlib.util.module_from_spec(loaded)
        loaded.loader.exec_module(module)
        return getattr(module, function)(**args)
    if ":" in spec:
        module_name, function = spec.split(":", 1)
        return getattr(importlib.import_module(module_name), function)(**args)
    package, _, name = spec.partition("/")
    try:
        return getattr(importlib.import_module(f"{package}.{name}"), name)(**args)
    except (ImportError, AttributeError):  # a task registered under a name that is not its module's
        from inspect_ai._util.registry import ensure_entry_points, registry_lookup

        importlib.import_module(package)
        ensure_entry_points()
        return registry_lookup("task", spec)(**args)


task = load_task(MODULE, LOAD_ARGS)
samples = {f"sample-{s.id if s.id is not None else i}": s for i, s in enumerate(task.dataset)}
init_active_model(get_model("mockllm/model"), GenerateConfig())


async def score(key, completion):
    """The task's own solver chain with a scripted model, then every scorer; the reward is their mean."""
    sample = samples[key]
    replies = [completion] if isinstance(completion, str) else [
        m.get("content") or "" for m in completion if m.get("role") == "assistant" and not m.get("tool_calls")] or [""]
    script = iter(replies)

    async def generate(state, *args, **kwargs):
        state.output = ModelOutput.from_content("scripted", next(script))
        state.messages.append(state.output.message)
        return state

    messages = [ChatMessageUser(content=sample.input)] if isinstance(sample.input, str) else list(sample.input)
    state = TaskState(model="scripted", sample_id=sample.id if sample.id is not None else key, epoch=1, input=sample.input,
                      messages=messages, target=Target(sample.target), choices=sample.choices, metadata=dict(sample.metadata or {}))
    state = await task.solver(state, generate)
    to_float, values = value_to_float(), []
    for scorer in task.scorer:
        value = (await scorer(state, Target(sample.target))).value
        values += [to_float(v) for v in value.values()] if isinstance(value, dict) else [to_float(value)]
    return sum(values) / len(values)
'''

