"""Turn probe results into a stand-alone reproduction script.

`falsepass repro <env>` writes `audits/<env>/repro_auto.py`: a script that depends only
on verifiers and the environment package, loads the same examples, scores the exact
completions recorded in `completions.json`, and prints observed against expected. A
finding that survives this script, run twice from clean virtualenvs, no longer depends
on falsepass being right.

Available for audits run in automatic mode (the loader is recorded there), and for a
hand-written adapter that declares how its data is loaded:

    loader = {"kind": "v0", "module": "my_env", "load_args": {}, "getter": "get_dataset"}

with example keys that end in the row's index (`train-17`). `kind` is `v0`, `v0-rollout`
or `v1`. An adapter that samples or filters its data in some other way keeps a
hand-written repro.
"""

from __future__ import annotations

import json
import re
import tomllib
from pathlib import Path
from typing import Any

from falsepass.cli import install_args

HEADER = '''"""Stand-alone repro for {env_id} {version} — generated by falsepass {falsepass}, {date}.

Depends only on {depends}. Run twice from a clean virtualenv:

  uv run --isolated --no-project --python 3.12 {install} python {path}

Each line prints: observed reward, the reward a correct verifier would give, and the case.
"""
import asyncio
import json
import re

CASES = json.loads({cases!r})
MODULE, LOAD_ARGS = {module!r}, {load_args!r}
'''

LOAD_V0 = '''
import verifiers as vf

env = vf.load_environment(MODULE, **LOAD_ARGS)
rows = env.{getter}()


def example(key):
    return rows[int(re.findall(r"[0-9]+", key)[-1])]
'''

SCORE_V0 = '''

async def score(key, completion):
    row = example(key)
    messages = [{"role": "assistant", "content": completion}] if isinstance(completion, str) else completion
    trajectory = [{"completion": [m]} for m in messages if m.get("role") == "assistant"]
    state = vf.State(input=dict(row), prompt=row["prompt"], completion=messages, trajectory=trajectory)
    await env.rubric.score_rollout(state)
    return state["reward"]
'''

SCORE_V0_ROLLOUT = '''
import time
from verifiers.types import Response, ResponseMessage


class Scripted(vf.Client):
    """Replies with the next line of a script; the environment supplies the user turns."""

    def __init__(self, script):
        super().__init__(object())
        self.script, self.calls = script, 0

    def setup_client(self, config): return None
    async def to_native_tool(self, tool): return tool
    async def to_native_prompt(self, messages): return messages, {}
    async def get_native_response(self, *args, **kwargs): raise NotImplementedError
    async def raise_from_native_response(self, response): return None
    async def from_native_response(self, response): return response
    async def close(self): return None

    async def get_response(self, prompt, model, tools=None, sampling_args=None, state=None, **kwargs):
        if self.calls >= 40:
            raise RuntimeError("rollout did not stop after 40 model turns")
        text = self.script[min(self.calls, len(self.script) - 1)]
        self.calls += 1
        message = ResponseMessage(role="assistant", content=text, finish_reason="stop", is_truncated=False)
        return Response(id=str(self.calls), created=int(time.time()), model=model, message=message)


async def score(key, completion):
    script = [completion] if isinstance(completion, str) else [m.get("content") for m in completion if m.get("role") == "assistant"]
    state = await env.rollout(dict(example(key)), Scripted(script or [""]), "scripted")
    await env.rubric.score_rollout(state)
    return state["reward"]
'''

LOAD_V1 = '''
import itertools

import verifiers.v1 as vf
from verifiers.v1.graph import MessageNode
from verifiers.v1.runtimes.subprocess import SubprocessConfig, SubprocessRuntime
from verifiers.v1.trace import AgentInfo, TraceTask
from verifiers.v1.utils.loaders import taskset_class

taskset = taskset_class(MODULE)(vf.taskset_config_type(MODULE)(id=MODULE, **LOAD_ARGS))
tasks = list(itertools.islice(iter(taskset.load()), {last} + 1))
runtime = SubprocessRuntime(SubprocessConfig())


async def score(key, completion):
    task = tasks[int(re.findall(r"[0-9]+", key)[-1])]
    if runtime.workdir is None:
        await runtime.start()
    trace = vf.Trace(task=TraceTask(type=type(task).__name__, data=task.data, key=task.key, hash=task.hash),
                     agent=AgentInfo(config=vf.AgentConfig()))
    trace.nodes.append(MessageNode(message=vf.UserMessage(content=task.data.prompt_text)))
    trace.nodes.append(MessageNode(parent=0, message=vf.AssistantMessage(content=completion), sampled=True))
    await task.score(trace, runtime)
    return trace.reward
'''

LOAD_INSPECT = '''
import importlib
import importlib.util
from pathlib import Path

from inspect_ai.model import ChatMessageUser, GenerateConfig, ModelOutput, get_model
from inspect_ai.model._model import init_active_model
from inspect_ai.scorer import Target, value_to_float
from inspect_ai.solver import TaskState


def load_task(spec, args):
    target, _, function = spec.partition("@")
    if target.endswith(".py"):
        loaded = importlib.util.spec_from_file_location("task_module", Path(target).resolve())
        module = importlib.util.module_from_spec(loaded)
        loaded.loader.exec_module(module)
        return getattr(module, function)(**args)
    if ":" in spec:
        module_name, function = spec.split(":", 1)
        return getattr(importlib.import_module(module_name), function)(**args)
    package, _, name = spec.partition("/")
    try:
        return getattr(importlib.import_module(f"{package}.{name}"), name)(**args)
    except (ImportError, AttributeError):  # a task registered under a name that is not its module's
        from inspect_ai._util.registry import ensure_entry_points, registry_lookup

        importlib.import_module(package)
        ensure_entry_points()
        return registry_lookup("task", spec)(**args)


task = load_task(MODULE, LOAD_ARGS)
samples = {f"sample-{s.id if s.id is not None else i}": s for i, s in enumerate(task.dataset)}
init_active_model(get_model("mockllm/model"), GenerateConfig())


async def score(key, completion):
    """The task's own solver chain with a scripted model, then every scorer; the reward is their mean."""
    sample = samples[key]
    replies = [completion] if isinstance(completion, str) else [
        m.get("content") or "" for m in completion if m.get("role") == "assistant" and not m.get("tool_calls")] or [""]
    script = iter(replies)

    async def generate(state, *args, **kwargs):
        state.output = ModelOutput.from_content("scripted", next(script))
        state.messages.append(state.output.message)
        return state

    messages = [ChatMessageUser(content=sample.input)] if isinstance(sample.input, str) else list(sample.input)
    state = TaskState(model="scripted", sample_id=sample.id if sample.id is not None else key, epoch=1, input=sample.input,
                      messages=messages, target=Target(sample.target), choices=sample.choices, metadata=dict(sample.metadata or {}))
    state = await task.solver(state, generate)
    to_float, values = value_to_float(), []
    for scorer in task.scorer:
        value = (await scorer(state, Target(sample.target))).value
        values += [to_float(v) for v in value.values()] if isinstance(value, dict) else [to_float(value)]
    return sum(values) / len(values)
'''

LOAD_HUD = '''
import os
from pathlib import Path

from hud import Taskset
from hud.environment import load_environment
from hud.environment.server import TaskRunner

PATH = Path(MODULE).resolve()
FOLDER = PATH if PATH.is_dir() else PATH.parent
os.chdir(FOLDER)  # environment hooks use paths relative to their folder
TASKS = list(Taskset.from_file(PATH).tasks.values())
BY_KEY = {t.slug or f"task-{i}": t for i, t in enumerate(TASKS)}
ENVIRONMENTS = {}


async def score(key, completion):
    """The task template's own grader, driven the way HUD's server drives it."""
    task = BY_KEY[key]
    if task.env not in ENVIRONMENTS:
        ENVIRONMENTS[task.env] = load_environment(FOLDER, name=task.env)
        await ENVIRONMENTS[task.env].start()
    reply = completion if isinstance(completion, str) else ([
        m.get("content") or "" for m in completion if m.get("role") == "assistant" and not m.get("tool_calls")] or [""])[-1]
    runner = TaskRunner(ENVIRONMENTS[task.env].tasks[task.id], task.args)
    await runner.start()
    return (await runner.grade({"answer": reply}))["score"]
'''

MAIN = '''

async def main():
    for case in CASES:
        try:
            observed = f"{await score(case['example'], case['completion']):.3f}"
        except Exception as exc:  # the reward code raising is itself the observation
            observed = f"raised {type(exc).__name__}"
        print(f"{observed:>8}  expected {case['expected']:<5} {case['probe']} {case['name']}/{case['variant']} on {case['example']}")


asyncio.run(main())
'''


def select(results: list[dict[str, Any]], completions: dict[str, Any], probes: list[str] | None, per_group: int) -> list[dict]:
    """Failing rows whose exact completion was kept: up to `per_group` examples per probe variant."""
    taken: dict[tuple, int] = {}
    cases = []
    for r in results:
        group = (r["probe"], r["name"], r["variant"])
        stored = completions.get(r["completion_id"])
        if isinstance(stored, str) and stored.startswith("Policy("):
            continue  # a reactive policy is code, not text; its repro is written by hand
        if r["passed"] or r["completion_id"] not in completions or (probes and r["probe"] not in probes):
            continue
        if taken.get(group, 0) >= per_group:
            continue
        taken[group] = taken.get(group, 0) + 1
        cases.append({
            "probe": r["probe"], "name": r["name"], "variant": r["variant"], "example": r["example"],
            "expected": "full" if r["expected"] == "full" else "0", "recorded": r["score"],
            "completion": completions[r["completion_id"]],
        })  # fmt: skip
    return cases


def generate(audit_dir: Path, probes: list[str] | None = None, per_group: int = 2) -> Path:
    payload = json.loads((audit_dir / "probe-results.json").read_text())
    loader = payload["meta"].get("loader")
    if not loader:
        raise RuntimeError(
            f"{audit_dir.name} was audited with a hand-written adapter that declares no `loader` (or before loaders "
            "were recorded): add a `loader` attribute to the adapter and re-run `falsepass audit`, or write the repro by hand"
        )
    completions = json.loads((audit_dir / "completions.json").read_text())
    cases = select(payload["results"], completions, probes, per_group)
    if not cases:
        raise RuntimeError("no failing probe with a stored completion to reproduce")
    env = tomllib.loads((audit_dir / "env.toml").read_text())["env"]
    path = audit_dir / "repro_auto.py"
    depends = {"inspect": "inspect_ai and the task's package", "hud": "the hud SDK and the environment's folder"}
    script = HEADER.format(
        env_id=env["id"], version=env.get("version", ""), install=" ".join(install_args(env)),
        falsepass=payload["meta"]["falsepass"], date=payload["meta"]["date"], path=path,
        module=loader.get("module") or loader.get("task"), load_args=loader.get("load_args", {}),
        cases=json.dumps(cases, ensure_ascii=True), depends=depends.get(loader["kind"], "verifiers and the environment package"),
    )  # fmt: skip
    if loader["kind"] == "inspect":
        script += LOAD_INSPECT
    elif loader["kind"] == "hud":
        script += LOAD_HUD
    elif loader["kind"] == "v1":
        script += LOAD_V1.replace("{last}", str(max(int(re.findall(r"[0-9]+", c["example"])[-1]) for c in cases)))
    else:
        script += LOAD_V0.format(getter=loader["getter"])
        script += SCORE_V0_ROLLOUT if loader["kind"] == "v0-rollout" else SCORE_V0
    path.write_text(script + MAIN)
    return path
