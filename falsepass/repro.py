import inspect


async def rubric_score(state):
    """`env.rubric.score_rollout(state)`; verifiers 0.1.8 and earlier also want a semaphore."""
    if "score_sem" not in inspect.signature(env.rubric.score_rollout).parameters:
        return await env.rubric.score_rollout(state)
    state["timing"] = state.get("timing") or {"generation_ms": 0.0, "scoring_ms": 0.0, "total_ms": 0.0}
