SCORE_V0_ROLLOUT = '''
import time


class Script:
    def __init__(self, script):
        self.script, self.calls = script, 0

    def next(self):
        if self.calls >= 40:
            raise RuntimeError("rollout did not stop after 40 model turns")
        self.calls += 1
        return self.script[min(self.calls - 1, len(self.script) - 1)]


class OpenAIStyle(Script):
    """verifiers without `vf.Client` (0.1.8 and earlier) calls `client.chat.completions.create`."""

    def __init__(self, script):
        super().__init__(script)
        self.chat = self.completions = self

    async def create(self, model, messages, **kwargs):
        from openai.types.chat import ChatCompletion

        message = {"role": "assistant", "content": self.next()}
        choice = {"index": 0, "finish_reason": "stop", "message": message}
        return ChatCompletion(id=str(self.calls), created=int(time.time()), model=model, object="chat.completion", choices=[choice])


class Scripted(getattr(vf, "Client", object)):
    """Replies with the next line of a script; the environment supplies the user turns."""

    def __init__(self, script):
        super().__init__(object())
        self.script, self.calls = script, 0

    def setup_client(self, config): return None
    async def to_native_tool(self, tool): return tool
    async def to_native_prompt(self, messages): return messages, {}
    async def get_native_response(self, *args, **kwargs): raise NotImplementedError
    async def raise_from_native_response(self, response): return None
    async def from_native_response(self, response): return response
    async def close(self): return None

    async def get_response(self, prompt, model, tools=None, sampling_args=None, state=None, **kwargs):
        from verifiers.types import Response, ResponseMessage

        if self.calls >= 40:
            raise RuntimeError("rollout did not stop after 40 model turns")
        text = self.script[min(self.calls, len(self.script) - 1)]
        self.calls += 1
        message = ResponseMessage(role="assistant", content=text, finish_reason="stop", is_truncated=False)
        return Response(id=str(self.calls), created=int(time.time()), model=model, message=message)


async def score(key, completion):
    script = [completion] if isinstance(completion, str) else [m.get("content") for m in completion if m.get("role") == "assistant"]
    client = (Scripted if hasattr(vf, "Client") else OpenAIStyle)(script or [""])
    state = await env.rollout(dict(example(key)), client, "scripted")
    await rubric_score(state)
    return state["reward"]
'''

