LOAD_OPENENV = '''
import importlib
import inspect
import os
import sys
import types
from pathlib import Path

FOLDER = Path(os.environ.get("FALSEPASS_SOURCE") or MODULE).resolve()
os.chdir(FOLDER)  # data files are read relative to the folder
sys.path.insert(0, str(FOLDER))
if ALIAS:  # the folder is its own package: `server/app.py` imports `<alias>.models`
    package = types.ModuleType(ALIAS)
    package.__path__ = [str(FOLDER)]
    sys.modules.setdefault(ALIAS, package)

try:
    from openenv.core.env_server.interfaces import Environment
except ImportError:  # the older openenv-core wheel
    from openenv_core.env_server.interfaces import Environment


def _load(spec):
    module, _, name = spec.partition(":")
    return getattr(importlib.import_module(module), name)


ACTION_CLASS = _load(ACTION_CLASS_SPEC)
ENV = (_load(FACTORY_SPEC) if FACTORY_SPEC else _load(ENV_CLASS_SPEC))()


async def _call(name, *args, **kwargs):
    """The async override when the environment has one (as openenv's server decides), else the sync method."""
    asynchronous = getattr(type(ENV), name + "_async", None)
    if asynchronous is not None and asynchronous is not getattr(Environment, name + "_async", None):
        return await asynchronous(ENV, *args, **kwargs)
    result = getattr(ENV, name)(*args, **kwargs)
    return await result if inspect.isawaitable(result) else result


def _reset_kwargs(key):
    """The reset keywords recorded for the task, filtered to what reset() accepts."""
    kwargs = RESETS.get(key, {})
    parameters = inspect.signature(ENV.reset).parameters
    if any(p.kind is inspect.Parameter.VAR_KEYWORD for p in parameters.values()):
        return kwargs
    return {k: v for k, v in kwargs.items() if k in parameters}


def _text(observation):
    """The observation's text, enough to tell one task from another."""
    data = observation.model_dump() if hasattr(observation, "model_dump") else observation
    parts = []

    def walk(value):
        if isinstance(value, dict):
            for v in value.values():
                walk(v)
        elif isinstance(value, (list, tuple)):
            for v in value:
                walk(v)
        elif isinstance(value, str):
            parts.append(value)

    walk(data)
    return " ".join(" ".join(parts).split())


async def score(key, completion):
    """The environment's own step() after a reset() to the task, as a WebSocket session does it.
    An environment that draws tasks at random is reset again until the audited task comes up."""
    reply = completion if isinstance(completion, str) else ([
        m.get("content") or "" for m in completion if m.get("role") == "assistant" and not m.get("tool_calls")] or [""])[-1]
    wanted = PROMPTS.get(key, "")
    for _ in range(RETRIES):
        observation = await _call("reset", **_reset_kwargs(key))
        if not wanted or wanted in _text(observation):
            break
    else:
        raise RuntimeError(f"reset() did not bring back task {key} in {RETRIES} tries")
    try:
        data = json.loads(reply)
    except ValueError:
        data = None
    named = isinstance(data, dict) and data and set(data) <= set(ACTION_CLASS.model_fields)
    fields = {**FILLS, **data} if named else {**FILLS, FIELD: reply} if FIELD else dict(FILLS)
    observation = await _call("step", ACTION_CLASS(**fields))
    reward = observation.reward
    return reward.get("value") if isinstance(reward, dict) else reward
'''

LOAD_REWARD = '''
import importlib
import importlib.util
import inspect
import os
import sys
import types
from pathlib import Path

sys.path[:0] = [p for p in PYTHONPATH if p not in sys.path]
if MODULE.endswith(".py"):
    PATH = Path(os.environ.get("FALSEPASS_SOURCE") or MODULE).resolve()
    if PATH.is_dir():  # a patched copy of the folder: the file of the same name in it
        PATH = PATH / Path(MODULE).name
    sys.path.insert(0, str(PATH.parent))
    os.chdir(PATH.parent)
    _spec = importlib.util.spec_from_file_location("rewards_under_test", PATH)
    REWARDS = importlib.util.module_from_spec(_spec)
    _spec.loader.exec_module(REWARDS)
else:
    REWARDS = importlib.import_module(MODULE)


def _arguments(row, text):
    """What GRPOTrainer passes a reward function for one completion."""
    prompt = row.get(PROMPT_COLUMN)
    if CONVERSATIONAL and not (isinstance(prompt, list) and prompt and isinstance(prompt[0], dict)):
        prompt = [{"role": "user", "content": str(prompt)}]
    completion = [{"role": "assistant", "content": text}] if CONVERSATIONAL else text
    state = types.SimpleNamespace(global_step=0, epoch=0.0, max_steps=0, num_train_epochs=0, log_history=[])
    kwargs = {"prompts": [prompt], "completions": [completion], "completion_ids": [[0] * max(1, round(len(text) / 4))],
              "trainer_state": state, "log_extra": lambda *a, **k: None, "log_metric": lambda *a, **k: None}
    kwargs.update({k: [v] for k, v in row.items() if k not in ("prompt", "completion", "completion_ids")})
    return kwargs


async def score(key, completion):
    """The weighted sum of the reward functions, None and NaN counting as nothing (GRPOTrainer's nansum)."""
    text = completion if isinstance(completion, str) else ([
        m.get("content") or "" for m in completion if m.get("role") == "assistant" and not m.get("tool_calls")] or [""])[-1]
    kwargs = _arguments(ROWS[key], text)
    total, given = 0.0, 0
    for name, weight in zip(FUNCTIONS, WEIGHTS):
        func = getattr(REWARDS, name)
        parameters = inspect.signature(func).parameters
        if not any(p.kind is inspect.Parameter.VAR_KEYWORD for p in parameters.values()):
            taken = {k: v for k, v in kwargs.items() if k in parameters}
        else:
            taken = kwargs
        value = func(**taken)
        if inspect.isawaitable(value):
            value = await value
        value = list(value)[0]
        if value is not None and value == value:
            total += weight * float(value)
            given += 1
    if not given:
        raise RuntimeError("every reward function returned None")
    return total
'''

MAIN = '''

async def main():
    for case in CASES:
        try:
            observed = f"{await score(case['example'], case['completion']):.6f}"
        except Exception as exc:  # the reward code raising is itself the observation
            observed = f"raised {type(exc).__name__}"
        print(f"{observed:>9}  expected {case['expected']:<5} {case['probe']} {case['name']}/{case['variant']} on {case['example']}")


asyncio.run(main())
'''


def select(results: list[dict[str, Any]], completions: dict[str, Any], probes: list[str] | None, per_group: int) -> list[dict]:
    """Failing rows whose exact completion was kept: up to `per_group` examples per probe variant."""
    taken: dict[tuple, int] = {}
    cases = []
    for r in results:
        group = (r["probe"], r["name"], r["variant"])
        stored = completions.get(r["completion_id"])
        if isinstance(stored, str) and stored.startswith("Policy("):
            continue  # a policy run from before episodes were kept: only its name is known
        if isinstance(stored, dict) and "script" in stored:  # a policy's episode: replay what it said, turn by turn
            if not stored["script"]:
                continue
            stored = stored["script"]
        if r["passed"] or r["completion_id"] not in completions or (probes and r["probe"] not in probes):
            continue
        if taken.get(group, 0) >= per_group:
            continue
        taken[group] = taken.get(group, 0) + 1
        cases.append({
            "probe": r["probe"], "name": r["name"], "variant": r["variant"], "example": r["example"],
            "expected": "full" if r["expected"] == "full" else "0", "recorded": r["score"],
            "completion": stored,
        })  # fmt: skip
    return cases


def generate(audit_dir: Path, probes: list[str] | None = None, per_group: int = 2) -> Path:
    payload = json.loads((audit_dir / "probe-results.json").read_text())
    loader = payload["meta"].get("loader")
    if not loader:
        raise RuntimeError(
            f"{audit_dir.name} was audited with a hand-written adapter that declares no `loader` (or before loaders "
            "were recorded). Add one to the adapter class and re-run the audit, e.g. "
            '`loader = {"kind": "v0", "module": "my_env", "load_args": {}, "getter": "get_dataset"}` for a legacy '
            'environment or `loader = {"kind": "v1", "module": "my_env", "load_args": {}}` for a v1 taskset, with example '
            "keys that end in the row's index (`row-17`, `task-17`); or write the repro by hand and run it with "
            "`repro --script`"
        )
    completions = json.loads((audit_dir / "completions.json").read_text())
    cases = select(payload["results"], completions, probes, per_group)
    if not cases:
        raise RuntimeError("no failing probe with a stored completion to reproduce")
    env = tomllib.loads((audit_dir / "env.toml").read_text())["env"]
    path = audit_dir / "repro_auto.py"
    depends = {"inspect": "inspect_ai and the task's package", "hud": "the hud SDK and the environment's folder",
               "openenv": "openenv and the environment folder with its own requirements",
               "reward": "the reward file and its own imports; the dataset rows are inlined"}  # fmt: skip
    script = HEADER.format(
        env_id=env["id"], version=env.get("version", ""), install=" ".join(install_args(env)), python=env.get("python", "3.12"),
        falsepass=payload["meta"]["falsepass"], date=payload["meta"]["date"], path=path,
        module=loader.get("module") or loader.get("task"), load_args=loader.get("load_args", {}),
        cases=json.dumps(cases, ensure_ascii=True), depends=depends.get(loader["kind"], "verifiers and the environment package"),
    )  # fmt: skip
    if loader["kind"] == "inspect":
        script += LOAD_INSPECT
    elif loader["kind"] == "hud":
        script += LOAD_HUD
    elif loader["kind"] == "reward":
        keys = {c["example"] for c in cases}
        settings = {"FUNCTIONS": loader["functions"], "WEIGHTS": loader["weights"], "CONVERSATIONAL": loader["conversational"],
                    "PYTHONPATH": loader.get("pythonpath", []),
                    "PROMPT_COLUMN": loader["prompt_column"], "ROWS": {k: v for k, v in loader.get("rows", {}).items() if k in keys}}  # fmt: skip
        script += "".join(f"{name} = json.loads({json.dumps(json.dumps(value, ensure_ascii=True, default=str))})\n"
                          for name, value in settings.items()) + LOAD_REWARD  # fmt: skip
    elif loader["kind"] == "openenv":
        keys = {c["example"] for c in cases}
        prompts = {k: " ".join(v.split()) for k, v in loader.get("prompts", {}).items() if k in keys}
        settings = {
            "ALIAS": loader.get("alias", ""), "ACTION_CLASS_SPEC": loader["action_class"], "FACTORY_SPEC": loader.get("factory", ""),
            "ENV_CLASS_SPEC": loader["env_class"], "FIELD": loader.get("field"), "FILLS": loader.get("fills", {}),
            "RESETS": {k: v for k, v in loader.get("resets", {}).items() if k in keys}, "PROMPTS": prompts,
            "RETRIES": loader.get("retries", 150),
        }  # fmt: skip
        script += "".join(f"{name} = {json.dumps(value, ensure_ascii=True)}\n" for name, value in settings.items()) + LOAD_OPENENV
    elif loader["kind"] == "v1":
        script += LOAD_V1.replace("{last}", str(max(int(re.findall(r"[0-9]+", c["example"])[-1]) for c in cases)))
    else:
        script += LOAD_V0.format(getter=loader["getter"])
        script += RUBRIC_SCORE + (SCORE_V0_ROLLOUT if loader["kind"] == "v0-rollout" else SCORE_V0)
    path.write_text(script + MAIN)
    return path
